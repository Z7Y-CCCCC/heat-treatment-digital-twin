const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const project = path.resolve(__dirname, '../..');
const output = path.join(project, 'output', 'collector-center-native-tests');
fs.mkdirSync(output, { recursive: true });
const build = spawnSync(process.execPath, [path.join(__dirname, 'build-collector-center.cjs')], { stdio: 'inherit', windowsHide: true });
if (build.error) throw build.error;
assert.equal(build.status, 0);
const executable = path.join(project, 'desktop', '.cache', 'collector-center', 'HeatTreatmentCollectorCenter.exe');
const report = path.join(output, `self-test-${Date.now()}.json`);
const result = spawnSync(executable, ['--self-test', report], { windowsHide: true, timeout: 30000 });
if (result.error) throw result.error;
const data = JSON.parse(fs.readFileSync(report, 'utf8').replace(/^\uFEFF/, ''));
assert.equal(result.status, 0, JSON.stringify(data)); assert.equal(data.success, true);
const launcher = fs.readFileSync(path.join(project, '采集运行中心.cmd'), 'utf8');
assert.match(launcher, /HeatTreatmentCollectorCenter\.exe/); assert.doesNotMatch(launcher, /electron|node\.exe/i);
const pkg = require('../package.json');
assert.ok(pkg.build.extraResources.some(r => r.to === 'collector-center'));
const shortcuts = fs.readFileSync(path.join(project, 'desktop', 'service-installer.nsh'), 'utf8');
assert.match(shortcuts, /采集运行中心\.lnk.*resources\\collector-center\\HeatTreatmentCollectorCenter\.exe/);
assert.ok(fs.statSync(executable).size < 512 * 1024, 'native center must remain under 512 KiB, no bundled browser/runtime');
console.log(JSON.stringify({ ...data, executableBytes: fs.statSync(executable).size, report }, null, 2));
