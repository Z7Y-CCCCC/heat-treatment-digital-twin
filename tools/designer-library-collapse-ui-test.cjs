// Isolated fixture; UI folding does not write any scene or global-view policy.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const playwright = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { createRunDirectory, startLoggedProcess, waitUntil } = require('../backend/scripts/integration-test-utils.cjs');
const { stopOwnedSmokeProcess } = require('../desktop/scripts/smoke-sandbox.cjs');
const directory = createRunDirectory('designer-library-collapse-ui');
const errors = [], checks = [];
let server, browser, page;
const pass = message => { checks.push(message); console.log('PASS ' + message); };
(async () => {
  const infoFile = path.join(directory, 'server.json');
  server = startLoggedProcess(process.execPath, [path.join(__dirname, 'manual-disassembly-ui-server.cjs')], {
    cwd: path.resolve(__dirname, '..'), env: { ...process.env, MANUAL_LAYOUT_UI_INFO_FILE: infoFile }, logFile: path.join(directory, 'server.log') });
  await waitUntil(() => { assert.equal(server.exitCode, null); return fs.existsSync(infoFile); }, 60000, 'owned folding backend');
  const info = JSON.parse(fs.readFileSync(infoFile));
  browser = await playwright.chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
  const context = await browser.newContext({ viewport: { width: 1600, height: 1050 } });
  await context.addInitScript(() => localStorage.setItem('digital_twin_admin_ui_state_v1', JSON.stringify({ activeTab: 'platform', platformSubpage: 'designer' })));
  page = await context.newPage(); page.setDefaultTimeout(15000); page.on('pageerror', error => errors.push(error.message));
  await page.goto(info.origin + '/admin');
  await page.getByRole('textbox', { name: '账号', exact: true }).fill(info.username);
  await page.getByLabel('后台密码', { exact: true }).fill(info.password);
  await page.getByRole('button', { name: '解锁后台', exact: true }).click();
  await page.locator('.dashboard-designer-shell').waitFor();
  const headings = page.locator('.component-group-heading');
  await headings.first().waitFor();
  assert.ok(await headings.count() >= 3);
  assert.equal(await headings.evaluateAll(elements => elements.every(element => element.getAttribute('aria-expanded') === 'false')), true);
  assert.equal(await page.locator('.component-grid').evaluateAll(elements => elements.every(element => getComputedStyle(element).display === 'none')), true);
  pass('all component categories default collapsed with a small triangular control');
  const data = page.getByRole('button', { name: '数据组件分类', exact: true });
  await data.click(); assert.equal(await data.getAttribute('aria-expanded'), 'true');
  await page.locator('[data-component-group="数据"] .component-grid').waitFor({ state: 'visible' });
  assert.equal(await page.getByRole('button', { name: '基础组件分类', exact: true }).getAttribute('aria-expanded'), 'false');
  await data.press('Enter'); assert.equal(await data.getAttribute('aria-expanded'), 'false');
  await data.press('Space'); assert.equal(await data.getAttribute('aria-expanded'), 'true');
  pass('category headers toggle independently using pointer and keyboard');
  const global = page.getByTestId('global-view-section');
  const globalHeader = global.locator('.section-heading');
  assert.equal(await globalHeader.getAttribute('aria-expanded'), 'false');
  assert.equal(await global.locator('.global-view-rows').count(), 0);
  await waitUntil(async () => await global.getByRole('switch', { name: '启用全部全局视角', exact: true }).isEnabled(), 10000, 'loaded global policy');
  const beforePolicy = await (await page.request.get(info.origin + '/api/view-navigation')).json();
  await globalHeader.click(); assert.equal(await globalHeader.getAttribute('aria-expanded'), 'true');
  assert.equal(await global.locator('.global-view-row').count(), 7);
  await globalHeader.press('Enter'); assert.equal(await globalHeader.getAttribute('aria-expanded'), 'false');
  const afterPolicy = await (await page.request.get(info.origin + '/api/view-navigation')).json();
  assert.deepEqual(afterPolicy.config, beforePolicy.config);
  pass('global views default folded; header folding preserves enabled policy and independent master switch');
  await page.reload(); await headings.first().waitFor();
  assert.equal(await headings.evaluateAll(elements => elements.every(element => element.getAttribute('aria-expanded') === 'false')), true);
  assert.equal(await globalHeader.getAttribute('aria-expanded'), 'false');
  await page.screenshot({ path: path.join(directory, 'collapsed-default.png') });
  assert.deepEqual(errors, []);
  pass('reload restores requested collapsed defaults without page errors');
  fs.writeFileSync(path.join(directory, 'report.json'), JSON.stringify({ checks, errors, directory }, null, 2));
  console.log('REPORT ' + directory);
})().catch(async error => { console.error(error); if (page) await page.screenshot({ path: path.join(directory, 'failure.png') }).catch(() => {}); process.exitCode = 1; })
  .finally(async () => { await browser?.close(); await stopOwnedSmokeProcess(server); });
