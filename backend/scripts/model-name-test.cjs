const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Database = require('better-sqlite3');
const { BACKEND_DIR, createRunDirectory, createTestDatabase, findFreePort, startLoggedProcess, waitForHttp, testFetch, forceStop } = require('./integration-test-utils.cjs');
let backend;
(async () => {
    const directory = createRunDirectory('model-name'), dataDir = path.join(directory, 'data'), filename = path.join(dataDir, 'factory.db');
    await createTestDatabase(filename);
    const db = new Database(filename), factoryId = db.prepare('SELECT factory_id FROM workshops LIMIT 1').get().factory_id;
    db.prepare('INSERT INTO factories (id,name) VALUES (?,?)').run('rename_other', '另一个工厂');
    const raw = '{  "LegacyCase": "ABC", "inspection": {"preserveLegacy": true}, "partBindings": [{"id":"keep"}] }';
    const insert = db.prepare('INSERT INTO models (id,name,file_path,factory_id,metadata,default_scale,placement_level) VALUES (?,?,?,?,?,2,?)');
    insert.run('rename_custom', '自建原名', '/uploads/models/custom.glb', factoryId, raw, 'device');
    insert.run('rename_foreign', '外厂原名', '/uploads/models/foreign.glb', 'rename_other', raw, 'device');
    insert.run('photo_washing_machine_v7', '外厂遮蔽', '/uploads/models/shadow.glb', 'rename_other', raw, 'device');
    const originalDevices = db.prepare('SELECT * FROM devices ORDER BY id').all();
    db.close();
    const origin = `http://127.0.0.1:${await findFreePort()}`;
    backend = startLoggedProcess(process.execPath, ['server.js'], { cwd: BACKEND_DIR, env: { ...process.env, APP_DATA_DIR: dataDir, DB_TYPE: 'sqlite', SQLITE_FILE: filename, PORT: new URL(origin).port, HOST: '127.0.0.1' }, logFile: path.join(directory, 'backend.log') });
    await waitForHttp(origin + '/api/health');
    let checks = 0;
    const api = async (id, body, expected = 200) => {
        const response = await testFetch(`${origin}/api/models/${id}/name`, { method: 'PUT', headers: { 'Content-Type': 'application/json', 'X-Factory-ID': factoryId }, body: JSON.stringify(body) });
        const data = await response.json(); assert.equal(response.status, expected, JSON.stringify(data)); checks++; return data;
    };
    const models = async () => (await (await testFetch(origin + '/api/models', { headers: { 'X-Factory-ID': factoryId } })).json());
    const before = await models(), custom = before.find(m => m.id === 'rename_custom');
    await api('rename_custom', { name: '  自定义名称  ' });
    assert.deepEqual((await models()).find(m => m.id === custom.id), { ...custom, name: '自定义名称' });
    for (const body of [{}, { name: '' }, { name: '  ' }, { name: 'a'.repeat(121) }, { name: 12 }, { name: ['bad'] }, { name: 'a\nb' }, { name: 'name', metadata: '{}' }, { name: 'name', file_path: '/bad' }]) await api('rename_custom', body, 400);
    const builtinId = 'pit_furnace_2_v1', builtin = before.find(m => m.id === builtinId);
    await api(builtinId, { name: '用户命名井式炉' });
    const renamedBuiltin = (await models()).find(m => m.id === builtinId);
    for (const key of Object.keys(builtin)) assert.deepEqual(renamedBuiltin[key], key === 'name' ? '用户命名井式炉' : builtin[key], key);
    await api('factory_hall_lowpoly', { name: '用户命名环境' });
    assert.equal((await models()).find(m => m.id === 'factory_hall_lowpoly').placement_level, 'factory');
    await api('not-a-model', { name: '不存在' }, 404);
    await api('rename_foreign', { name: '禁止修改' }, 404);
    await api('photo_washing_machine_v7', { name: '不能覆盖外厂行' }, 404);
    const stored = new Database(filename);
    assert.equal(stored.prepare('SELECT metadata FROM models WHERE id=?').get('rename_custom').metadata, raw);
    assert.equal(stored.prepare('SELECT name FROM models WHERE id=?').get('rename_foreign').name, '外厂原名');
    assert.equal(stored.prepare('SELECT name FROM models WHERE id=?').get('photo_washing_machine_v7').name, '外厂遮蔽');
    assert.deepEqual(stored.prepare('SELECT * FROM devices ORDER BY id').all(), originalDevices);
    stored.close();
    console.log(JSON.stringify({ success: true, checks, narrowNameOnly: true, builtinPersistence: true, factoryIsolation: true, metadataBytesPreserved: true, directory }, null, 2));
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => forceStop(backend));
